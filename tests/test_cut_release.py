"""scripts/cut_release.py: the version bump a release commits, without git or gh."""
import importlib.util
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("cut_release", ROOT / "scripts/cut_release.py")
cut_release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cut_release)

CARGO_TOML = """[workspace]
members = ["crates/*", "apps/demo"]

[workspace.package]
version = "0.18.1"
edition = "2024"

[workspace.dependencies]
demo-geom = { path = "crates/geom", version = "0.18.1" }
demo-io = { path = "crates/io", version = "0.18.1" }
serde = { version = "0.18.1" }
craft-update = { git = "https://github.com/storytold/craft-libs", version = "=0.1.0", rev = "abc" }
"""

CARGO_LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo"
version = "0.18.1"
dependencies = [
 "demo-geom",
]

[[package]]
name = "demo-geom"
version = "0.18.1"

[[package]]
name = "serde"
version = "0.18.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "xtask"
version = "0.1.0"
"""


class NextVersion(unittest.TestCase):
    def test_minor_and_patch(self):
        self.assertEqual(cut_release.next_version("v0.20.0", "minor"), "0.21.0")
        self.assertEqual(cut_release.next_version("0.23.1", "minor"), "0.24.0")
        self.assertEqual(cut_release.next_version("v0.23.1", "patch"), "0.23.2")

    def test_a_prerelease_patch_is_the_release_itself(self):
        self.assertEqual(cut_release.next_version("v0.3.0-rc.1", "patch"), "0.3.0")

    def test_rejects_what_is_not_a_version(self):
        with self.assertRaises(ValueError):
            cut_release.next_version("nightly", "minor")


class Bump(unittest.TestCase):
    def repo(self, toml=CARGO_TOML, lock=CARGO_LOCK, crlf=False):
        d = Path(tempfile.mkdtemp())
        nl = "\r\n" if crlf else "\n"
        (d / "Cargo.toml").write_bytes(toml.replace("\n", nl).encode())
        (d / "Cargo.lock").write_bytes(lock.replace("\n", nl).encode())
        return d

    def test_bumps_the_workspace_its_path_dependencies_and_its_own_lock_entries(self):
        d = self.repo()
        old, lines, packages = cut_release.bump_cargo(d, "0.21.0")
        self.assertEqual((old, lines, packages), ("0.18.1", 3, 2))
        toml = (d / "Cargo.toml").read_text()
        self.assertIn('[workspace.package]\nversion = "0.21.0"', toml)
        self.assertIn('demo-geom = { path = "crates/geom", version = "0.21.0" }', toml)
        # A registry dependency that happens to share the version is not the workspace's.
        self.assertIn('serde = { version = "0.18.1" }', toml)
        lock = (d / "Cargo.lock").read_text()
        self.assertIn('name = "demo"\nversion = "0.21.0"', lock)
        self.assertIn('name = "demo-geom"\nversion = "0.21.0"', lock)
        self.assertIn('name = "serde"\nversion = "0.18.1"\nsource', lock)
        self.assertIn('name = "xtask"\nversion = "0.1.0"', lock)
        self.assertEqual(cut_release.workspace_version(d), "0.21.0")

    def test_keeps_crlf_files_crlf(self):
        d = self.repo(crlf=True)
        cut_release.bump_cargo(d, "0.21.0")
        for name in ("Cargo.toml", "Cargo.lock"):
            raw = (d / name).read_bytes()
            self.assertNotIn(b"\n", raw.replace(b"\r\n", b""), name)

    def test_refuses_a_bump_to_the_same_version_or_a_bad_one(self):
        d = self.repo()
        with self.assertRaises(ValueError):
            cut_release.bump_cargo(d, "0.18.1")
        with self.assertRaises(ValueError):
            cut_release.bump_cargo(d, "0.21")

    def test_runs_the_repositorys_own_hook_with_old_and_new(self):
        d = self.repo()
        (d / "packaging").mkdir()
        (d / cut_release.HOOK).write_text("#!/bin/bash\n")
        calls = []
        old = cut_release.bump(d, "0.21.0", run=lambda cmd, **kw: calls.append((cmd, kw["cwd"])))
        self.assertEqual(old, "0.18.1")
        self.assertEqual(calls, [(["bash", cut_release.HOOK, "0.18.1", "0.21.0"], d)])

    def test_no_hook_no_call(self):
        d = self.repo()
        calls = []
        cut_release.bump(d, "0.21.0", run=lambda *a, **kw: calls.append(a))
        self.assertEqual(calls, [])


if __name__ == "__main__":
    unittest.main()
